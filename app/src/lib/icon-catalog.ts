// Entradas que ofrece cada consumidor: las cuentas no usan las de `scope: 'category'`.
export function iconsForScope(scope: 'account' | 'category'): readonly IconEntry[] {
  return scope === 'category'
    ? ICON_CATALOG
    : ICON_CATALOG.filter((entry) => entry.scope !== 'category');
}

export function findIcon(entries: readonly IconEntry[], key: string | null | undefined) {
  if (key === null || key === undefined) return null;
  return entries.find((entry) => entry.key === key) ?? null;
}

// Grupos que tienen al menos una entrada, en el orden del catálogo.
export function groupsOf(entries: readonly IconEntry[]): string[] {
  return ICON_GROUPS.filter((group) => entries.some((entry) => entry.group === group));
}

export function entriesOfGroup(entries: readonly IconEntry[], group: string): IconEntry[] {
  return entries.filter((entry) => entry.group === group);
}

// Grupo inicial del selector: el del ícono actual o, sin ícono o con clave desconocida, el primero.
export function initialGroup(entries: readonly IconEntry[], key: string | null): string {
  const groups = groupsOf(entries);
  return findIcon(entries, key)?.group ?? groups[0] ?? '';
}

// Minúsculas y sin tildes («Baño» -> «bano»).
export function normalizeSearch(text: string): string {
  return text.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase().trim();
}

// Entradas cuyo nombre o palabras clave contienen el texto, en el orden del catálogo. Texto vacío = [].
export function searchIcons(entries: readonly IconEntry[], query: string): IconEntry[] {
  const needle = normalizeSearch(query);
  if (needle === '') return [];
  return entries.filter((entry) =>
    [entry.name, ...entry.keywords].some((word) => normalizeSearch(word).includes(needle)),
  );
}
