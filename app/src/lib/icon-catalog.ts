// P2). 249 entradas en 17 grupos. La API solo valida la clave (`^[a-z0-9-]{1,20}$`); el emoji, el nombre,
// el grupo y las palabras clave viven solo en la app. Las 35 claves anteriores (12 de cuenta y 30 de
// categoría, 7 comunes) conservan clave, emoji y nombre: no se renombran nunca (hay datos guardados).
// Emoji de Unicode 10 o anterior, sin ZWJ ni tonos de piel. Puro y sin dependencias de React.

// `category`: la entrada solo se ofrece al elegir ícono de categoría (glifos de texto ⋯ y ＋ y la etiqueta
// predeterminada `tag`); sin `scope` sirve para cuentas y categorías.
export type IconScope = 'category';

export interface IconEntry {
  key: string;
  glyph: string;
  // Nombre en español: etiqueta accesible «Ícono {nombre}» (único en todo el catálogo).
  name: string;
  group: string;
  // Palabras clave en español para el buscador (la búsqueda normaliza tildes y mayúsculas).
  keywords: readonly string[];
  // true: glifo de texto que se dibuja en el color de texto o en blanco (los emojis llevan su color).
  text?: true;
  scope?: IconScope;
}

